map("n", "gR", function()
  vscode.call("references-view.find")
end)
map("n", "gr", function()
  vscode.call("editor.action.referenceSearch.trigger")
end)
map("n", "gH", function()
  vscode.call("references-view.showCallHierarchy")
end)
map("n", "gh", function()
  vscode.call("editor.showCallHierarchy")
end)
map("n", "gI", function()
  vscode.call("references-view.findImplementations")
end)
map("n", "gi", function()
  vscode.call("editor.action.peekImplementation")
end)

-- bookmarks
map("n", "<space>mm", function()
  vscode.call("bookmarks.toggle")
end)
map("n", "<space>mn", function()
  vscode.call("bookmarks.jumpToNext")
end)
map("n", "<space>mp", function()
  vscode.call("bookmarks.jumpToPrevious")
end)
map("n", "<space>ml", function()
  vscode.call("bookmarks.list")
end)
map("n", "<space>ma", function()
  vscode.call("bookmarks.listFromAllFiles")
end)
map("n", "<space>mc", function()
  vscode.call("bookmarks.clear")
end)
map("n", "<space>me", function()
  vscode.call("bookmarksExplorer.focus")
end)

-- textmarker
map("n", "<space>tt", function()
  vscode.call("textmarker.toggleHighlight")
end)
map("n", "<space>tc", function()
  vscode.call("textmarker.clearAllHighlight")
end)
map("n", "<space>tn", function()
  vscode.call("textmarker.gotToNextHighlight")
end)
map("n", "<space>tp", function()
