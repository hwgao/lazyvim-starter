vim.keymap.set("n", "<Esc>", "<Esc>:nohlsearch<CR>", { silent = true })
vim.keymap.set("n", "<space>{", "?^\\S.*{$<CR>:noh<CR>", { silent = true })
vim.keymap.set("n", "<space>}", "/^}$<CR>:noh<CR>", { silent = true })

-- NOTE: Skip use group key: m -- bookmarks, t -- textmarker
local vscode = require("vscode")
local map = function(mode, lhs, cmd, opts)
  opts = opts or { silent = true }
  vim.keymap.set(mode, lhs, cmd, opts)
end

map("n", "<space><space>", function()
  vscode.call("workbench.action.quickOpen")
end)
map("n", "<space>,", function()
  vscode.call("workbench.action.showAllEditors")
end)
map("n", "<space>s", function()
  vscode.call("workbench.action.gotoSymbol")
end)
-- skip <space>m
map("n", "<space>o", function()
  vscode.call("workbench.action.closeSidebar")
  vscode.call("workbench.action.closeAuxiliaryBar")
  vscode.call("workbench.action.closePanel")
end)
-- skip <space>t
map("n", "<space>z", function()
  vscode.call("workbench.action.toggleZenMode")
end)
-- Enable search: Seed with nearest word
map("n", "<space>/", function()
  vscode.call("workbench.action.findInFiles")
end)

-- clipboard copy/paste
vim.keymap.set("", "<space>y", '"+y')
vim.keymap.set("", "<space>x", '"+dd')
vim.keymap.set("", "<space>p", '"+p')

